function v = fitted(ax, make)
% The limits around what make draws in a transform turned by pi/6.
cla(ax);
tr = hgtransform(ax);
tr.Matrix = makehgtform('zrotate', pi/6);
make(tr);
drawnow;
v = round([ax.XLim, ax.YLim], 12);
end

function v = setget(h, name, value)
set(h, name, value);
