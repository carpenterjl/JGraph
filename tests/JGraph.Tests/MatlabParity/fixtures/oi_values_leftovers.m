function out = run_row(code__)
try
    eval(code__);
    out = describe(r);
catch err__
    out = sprintf('ERR %s / %s', err__.identifier, strrep(err__.message, newline, ' / '));
end
out = strrep(out, '|', '!');
end

function s = describe(v)
c = class(v);
z = mat2str(size(v));
if isstruct(v)
    f = fieldnames(v);
    if isempty(v)
        s = sprintf('%s %s {%s}', c, z, strjoin(f', ','));
    else
        parts = cell(1, numel(v));
        for q = 1:numel(v)
            parts{q} = flat(v(q));
        end
        s = sprintf('%s %s {%s} %s', c, z, strjoin(f', ','), strjoin(parts, ' ; '));
    end
elseif iscell(v)
    parts = cellfun(@flat, v(:)', 'UniformOutput', false);
    s = sprintf('%s %s {%s}', c, z, strjoin(parts, ','));
elseif isdatetime(v) || isduration(v) || iscategorical(v) || iscalendarduration(v)
    if isempty(v)
        s = sprintf('%s %s []', c, z);
    else
        s = sprintf('%s %s [%s]', c, z, strjoin(cellstr(string(v(:)')), ','));
    end
elseif ischar(v) && size(v, 1) > 1
    s = sprintf('%s %s %s', c, z, strjoin(cellfun(@flat, arrayfun(@(q) v(q, :), 1:size(v, 1), 'UniformOutput', false), 'UniformOutput', false), '/'));
else
    s = sprintf('%s %s %s', c, z, flat(v));
end
end

function s = flat(v)
if isstruct(v)
    f = fieldnames(v);
    parts = cell(1, numel(f));
    for q = 1:numel(f)
        parts{q} = [f{q} '=' flat(v.(f{q}))];
    end
    s = ['<' strjoin(parts, ',') '>'];
elseif ischar(v)
    s = ['''' strrep(strrep(v, newline, '\n'), char(9), '\t') ''''];
elseif isstring(v)
    s = ['"' char(strjoin(v, '","')) '"'];
elseif iscell(v)
    s = ['{' strjoin(cellfun(@flat, v(:)', 'UniformOutput', false), ',') '}'];
elseif isnumeric(v) || islogical(v)
    s = [class(v) ':' mat2str(v)];
elseif isa(v, 'function_handle')
    s = func2str(v);
else
    s = ['<' class(v) ' ' mat2str(size(v)) '>'];
end
end
