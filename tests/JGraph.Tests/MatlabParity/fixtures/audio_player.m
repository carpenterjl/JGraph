ix_chk('c_cplx', sprintf('%d', get(audioplayer(complex(zeros(10,1)), 8000), 'TotalSamples')));
ix_chk('c_3d', sprintf('%d %d', get(audioplayer(zeros(10,1,2), 8000), 'TotalSamples'), get(audioplayer(zeros(10,1,2), 8000), 'NumChannels')));
