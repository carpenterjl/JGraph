p = audioplayer(zeros(4000, 2), 8000);
ix_chk('class', class(p));
ix_chk('isa', sprintf('%d %d %d', isa(p, 'handle'), isa(p, 'matlab.mixin.SetGet'), isobject(p)));
ix_chk('props', strjoin(properties(p)', ','));
ix_chk('defaults', sprintf('%g %d %d %d %d %d %s %g %s %s', p.SampleRate, p.BitsPerSample, p.NumChannels, p.DeviceID, ...
    p.CurrentSample, p.TotalSamples, p.Running, p.TimerPeriod, p.Type, class(p.Tag)));
ix_chk('empty_fcns', sprintf('%d %d %d %d', isempty(p.StartFcn), isempty(p.StopFcn), isempty(p.TimerFcn), isempty(p.UserData)));
ix_chk('hidden_channels', sprintf('%d', p.NumberOfChannels));
ix_chk('get_cell', strjoin(cellfun(@(v) class(v), get(p, {'Tag', 'SampleRate'}), 'UniformOutput', false), ','));
ix_chk('get_trunc', sprintf('%g', get(p, 'samp')));
ix_chk('dot_trunc', sprintf('%g', p.samp));
ix_chk('dot_upper', sprintf('%g', p.SAMPLERATE));
ix_chk('dot_ambig', dv_err(@() p.S));
ix_chk('dot_ambig_t', dv_err(@() p.T));
ix_chk('get_ambig', dv_err(@() get(p, 'St')));
ix_chk('get_bogus', dv_err(@() get(p, 'Bogus')));
ix_chk('dot_bogus', dv_err(@() p.Bogus));
% JGraph's sentence for an unknown function does not name the argument's class (div=ADR0193).
ix_chk('method_upper', dv_err(@() ISPLAYING(p)));
set(p, 'Tag', "hello");
ix_chk('set_tag', class(p.Tag));
ix_chk('set_tag_num', dv_err(@() set(p, 'Tag', 5)));
ix_chk('set_tag_strarr', dv_err(@() set(p, 'Tag', ["a" "b"])));
p.samp = 16000;
ix_chk('set_dot_trunc', sprintf('%g', p.SampleRate));
set(p, 'ta', 'y');
ix_chk('set_trunc', p.Tag);
ix_chk('set_ambig', dv_err(@() set(p, 'S', 1)));
ix_chk('set_fs_bad', dv_err(@() set(p, 'SampleRate', 10)));
ix_chk('set_fs_char', dv_err(@() set(p, 'SampleRate', 'a')));
ix_chk('set_bits', dv_err(@() set(p, 'BitsPerSample', 8)));
ix_chk('set_total', dv_err(@() set(p, 'TotalSamples', 8)));
ix_chk('set_period_small', dv_err(@() set(p, 'TimerPeriod', 0.0001)));
ix_chk('set_period_neg', dv_err(@() set(p, 'TimerPeriod', -1)));
ix_chk('set_period_vec', dv_err(@() set(p, 'TimerPeriod', [1 2])));
ix_chk('set_period_char', dv_err(@() set(p, 'TimerPeriod', 'a')));
ix_chk('set_fcn_num', dv_err(@() set(p, 'StartFcn', 5)));
p.StartFcn = 'x = 1;';
p.StopFcn = {@disp, 1};
ix_chk('set_fcn_text_cell', sprintf('%s %s', class(p.StartFcn), class(p.StopFcn)));
p.StartFcn = [];
p.StopFcn = [];
ix_chk('set_bogus', dv_err(@() set(p, 'Bogus', 1)));
ix_chk('concat', dv_err(@() [p p]));
ix_chk('concat_one', class([p]));
ix_chk('isplaying', mat2str(isplaying(p)));
ix_chk('play_bad_idx', dv_err(@() play(p, [1 2 3])));
ix_chk('play_char_idx', dv_err(@() play(p, 'a')));
ix_chk('play_empty_idx', dv_err(@() play(p, [])));
ix_chk('play_three', dv_err(@() play(p, 1, 2)));
lastwarn('');
play(p, [5 2]);
[~, id] = lastwarn;
ix_chk('play_backwards', sprintf('%s %d', id, isplaying(p)));
stop(p);
lastwarn('');
play(p, 0);
[~, id] = lastwarn;
ix_chk('play_zero', id);
stop(p);
ix_chk('stopped', sprintf('%s %d', p.Running, p.CurrentSample));

q = audioplayer(zeros(4000, 1), 8000);
q.StartFcn = @(o, e) audio_log('start', o, e);
q.StopFcn = @(o, e) audio_log('stop', o, e);
q.TimerFcn = @(o, e) audio_log('timer', o, e);
q.TimerPeriod = 0.1;
audio_log('clear');
play(q);
ix_chk('play_running', q.Running);
ix_chk('play_log', audio_log());
pause(1);
ix_chk('done_log', audio_log());
ix_chk('done_state', sprintf('%s %d', q.Running, q.CurrentSample));
audio_log('clear');
playblocking(q);
ix_chk('blocking_log', audio_log());
ix_chk('blocking_state', sprintf('%s %d', q.Running, q.CurrentSample));
audio_log('clear');
play(q); pause(0.2); pause(q);
ix_chk('paused_log', audio_log());
ix_chk('paused_state', sprintf('%s %d', q.Running, q.CurrentSample > 1 && q.CurrentSample < 4000));
audio_log('clear');
resume(q); pause(0.05);
ix_chk('resumed_log', audio_log());
ix_chk('resumed_running', q.Running);
stop(q);
ix_chk('stopped_log', audio_log());
ix_chk('stopped_state', sprintf('%s %d', q.Running, q.CurrentSample));
audio_log('clear');
stop(q); pause(q);
ix_chk('stop_again_log', ['[' audio_log() ']']);
audio_log('clear');
q.StopFcn = {@audio_log, 'cellstop'};
playblocking(q, [1 800]);
ix_chk('cell_callback', audio_log());
q.StartFcn = @(o, e) error('my:id', 'boom');
q.StopFcn = [];
ix_chk('start_error', dv_err(@() play(q)));
ix_chk('start_error_state', q.Running);
delete(q);
ix_chk('deleted', sprintf('%d %s', isvalid(q), dv_err(@() q.SampleRate)));

