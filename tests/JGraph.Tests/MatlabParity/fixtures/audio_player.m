% audio_player.m -- audioplayer (device classes plan, stage D10): its constructor's checks, its
% properties' setters, names read case-blind and shortened, play's selections, the callbacks' order
% around play, pause, resume, stop and playblocking, and sound and soundsc. Recorded from R2025b on
% this machine's output, playing only zeros; JGraph plays to jgraph.internal.audiosim's outputs
% (audio_env), so neither is heard. Rows that depend on how fast a device starts (TimerFcn counts,
% the sample reached after a given pause) are left out.

