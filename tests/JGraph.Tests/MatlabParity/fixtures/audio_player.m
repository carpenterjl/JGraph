    get(audioplayer(int16(zeros(10,1)), 8000), 'BitsPerSample'), get(audioplayer(uint8(zeros(10,1)), 8000), 'BitsPerSample'), ...
    get(audioplayer(int8(zeros(10,1)), 8000), 'BitsPerSample'), get(audioplayer(zeros(10,1), 8000, 24), 'BitsPerSample')));
