'v17', 's = struct(''a'', {}); s.a = 5;', 's'
'v18', 's = struct(''a'', {1; 2}); s.a = 5;', 's'
'v19', 'T = table([1; 2], [3; 4], ''VariableNames'', {''p'', ''q''}); y = T{:, ''q''};', 'y'
