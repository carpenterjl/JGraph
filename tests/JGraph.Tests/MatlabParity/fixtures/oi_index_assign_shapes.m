};
for k = 1:size(cases, 1)
    oi_run_case(cases{k, 1}, cases{k, 2}, cases{k, 3});
end

% Each case runs in a workspace of its own, so one case's names do not reach the next.
function oi_run_case(key, code, var)
try
    eval(code);
    v = eval(var);
    fprintf('CHK|%s|%s %s %s|exact\n', key, class(v), mat2str(size(v)), oi_show(v));
catch err
    fprintf('CHK|%s|ERR %s %s|exact\n', key, err.identifier, err.message);
end
end

function t = oi_show(v)
if isstruct(v)
    f = fieldnames(v);
    parts = cell(1, numel(v));
    for k = 1:numel(v)
        if isempty(f)
            parts{k} = '-';
        else
            parts{k} = oi_show(v(k).(f{1}));
        end
    end
    t = ['{' strjoin(f', ',') '} ' strjoin(parts, ' ')];
elseif iscell(v)
    parts = cell(1, numel(v));
    for k = 1:numel(v)
        parts{k} = oi_show(v{k});
    end
    t = ['{' strjoin(parts, ' ') '}'];
elseif isstring(v)
    t = ['"' strjoin(cellstr(v(:)'), '","') '"'];
elseif ischar(v)
    t = ['''' v(:)' ''''];
else
    t = mat2str(double(v(:)'));
end
end
