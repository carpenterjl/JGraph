% serial_lines.m -- serialport's terminated text and binblocks (device classes plan, stage D1):
% configureTerminator's forms and refusals, writeline, readline (a timeout answers [] with a
% warning and leaves the partial line), writeread (a timeout is an error), and IEEE 488.2
% definite-length blocks both ways. The peer logs and sends raw bytes.

s = dv_open();
writeline(s, "abc");
ix_chk('writeline_lf', ix_show(dp(s, 'recv')));
writeline(s, 'chars');
ix_chk('writeline_char', ix_show(dp(s, 'recv')));
ix_chk('writeline_num', dv_err(@() writeline(s, 65)));
ix_chk('writeline_strarr', dv_err(@() writeline(s, ["a" "b"])));
ix_chk('writeline_cell', dv_err(@() writeline(s, {'a'})));
ix_chk('writeline_none', dv_err(@() writeline(s)));
ix_chk('writeline_two', dv_err(@() writeline(s, "a", "b")));
ix_chk('writeline_empty', dv_err(@() writeline(s, "")));
ix_chk('writeline_charmat', dv_err(@() writeline(s, ['ab'; 'cd'])));
ix_chk('nothing_sent', ix_show(dp(s, 'recv')));

% the terminators
configureTerminator(s, "CR");
ix_chk('term_cr', ix_show(s.Terminator));
writeline(s, "x");
ix_chk('writeline_cr', ix_show(dp(s, 'recv')));
configureTerminator(s, "CR/LF");
ix_chk('term_crlf', ix_show(s.Terminator));
writeline(s, "x");
ix_chk('writeline_crlf', ix_show(dp(s, 'recv')));
configureTerminator(s, 0);
ix_chk('term_zero', ix_show(s.Terminator));
writeline(s, "x");
ix_chk('writeline_zero', ix_show(dp(s, 'recv')));
configureTerminator(s, "LF", "CR");
ix_chk('term_pair', ix_show(s.Terminator));
writeline(s, "x");
ix_chk('writeline_pair', ix_show(dp(s, 'recv')));
configureTerminator(s, 13, "LF");
ix_chk('term_pair_num', ix_show(s.Terminator));
configureTerminator(s, "cr");
ix_chk('term_lower', ix_show(s.Terminator));
configureTerminator(s, 'C');
ix_chk('term_partial', ix_show(s.Terminator));
configureTerminator(s, int8(10));
ix_chk('term_int8', ix_show(s.Terminator));
ix_chk('term_bad', dv_err(@() configureTerminator(s, "TAB")));
ix_chk('term_256', dv_err(@() configureTerminator(s, 256)));
ix_chk('term_neg', dv_err(@() configureTerminator(s, -1)));
ix_chk('term_frac', dv_err(@() configureTerminator(s, 1.5)));
ix_chk('term_vec', dv_err(@() configureTerminator(s, [10 13])));
ix_chk('term_none', dv_err(@() configureTerminator(s)));
ix_chk('term_three', dv_err(@() configureTerminator(s, "LF", "LF", "LF")));
ix_chk('term_lfcr', dv_err(@() configureTerminator(s, "LF/CR")));
ix_chk('term_char_num', dv_err(@() configureTerminator(s, '10')));
ix_chk('term_pair_bad', dv_err(@() configureTerminator(s, "LF", 300)));
ix_chk('term_kept', ix_show(s.Terminator));

% readline
configureTerminator(s, "LF");
flush(s);
dp(s, sprintf('send %s', dp_hex(['one' 10 'two' 10 'three'])));
pause(0.3);
ix_chk('readline_1', ix_show(readline(s)));
ix_chk('readline_2', ix_show(readline(s)));
[v, w] = dv_warn(@() readline(s));
ix_chk('readline_partial', ix_show(v));
ix_chk('readline_partial_warn', w);
ix_chk('readline_partial_left', s.NumBytesAvailable);
flush(s);
[v, w] = dv_warn(@() readline(s));
ix_chk('readline_none', ix_show(v));
ix_chk('readline_none_warn', w);
ix_chk('readline_arg', dv_err(@() readline(s, 1)));
dp(s, sprintf('send %s', dp_hex([10 10 'a' 13 10])));
pause(0.3);
ix_chk('readline_empty_line', ix_show(readline(s)));
ix_chk('readline_empty_2', ix_show(readline(s)));
ix_chk('readline_cr_kept', ix_show(double(char(readline(s)))));
configureTerminator(s, "CR/LF");
flush(s);
dp(s, sprintf('send %s', dp_hex(['a' 10 'b' 13 'c' 13 10 'd' 13 10])));
pause(0.3);
ix_chk('readline_crlf_1', ix_show(double(char(readline(s)))));
ix_chk('readline_crlf_2', ix_show(double(char(readline(s)))));
configureTerminator(s, 13);
flush(s);
dp(s, sprintf('send %s', dp_hex(['p' 13 'q' 10 13])));
pause(0.3);
ix_chk('readline_int_1', ix_show(double(char(readline(s)))));
ix_chk('readline_int_2', ix_show(double(char(readline(s)))));
configureTerminator(s, "CR", "LF");
flush(s);
dp(s, sprintf('send %s', dp_hex(['r' 13 's' 10])));
pause(0.3);
ix_chk('readline_pair_reads_cr', ix_show(double(char(readline(s)))));
configureTerminator(s, 0);
flush(s);
dp(s, sprintf('send %s', dp_hex(['z' 0 'y' 0])));
pause(0.3);
ix_chk('readline_nul', ix_show(double(char(readline(s)))));
configureTerminator(s, "LF");
flush(s);
dp(s, sprintf('send %s', dp_hex([104 233 108 108 111 10])));
pause(0.3);
ix_chk('readline_high', ix_show(double(char(readline(s)))));
dp(s, sprintf('send %s', dp_hex([195 169 10])));
pause(0.3);
ix_chk('readline_utf8_bytes', ix_show(double(char(readline(s)))));
dp(s, sprintf('send %s', dp_hex(['ab' 10 'cd'])));
pause(0.3);
readline(s);
ix_chk('read_after_readline', ix_show(read(s, 2, "char")));

% writeread, with the peer echoing
flush(s);
dp(s, 'echo on');
ix_chk('writeread', ix_show(writeread(s, "hello")));
ix_chk('writeread_char', ix_show(writeread(s, 'abc')));
ix_chk('writeread_none', dv_err(@() writeread(s)));
ix_chk('writeread_num', dv_err(@() writeread(s, 5)));
dp(s, 'echo off');
ix_chk('writeread_timeout', dv_err(@() writeread(s, "q")));
flush(s);
dp(s, 'recv');

% binblock out
writebinblock(s, 1:5, "uint8");
ix_chk('wbb_uint8', ix_show(dp(s, 'recv')));
writebinblock(s, [1 2], "uint16");
ix_chk('wbb_uint16', ix_show(dp(s, 'recv')));
writebinblock(s, 1:12, "uint8", "HDR");
ix_chk('wbb_header', ix_show(dp(s, 'recv')));
writebinblock(s, 'hi', "char");
ix_chk('wbb_char', ix_show(dp(s, 'recv')));
writebinblock(s, 1:300, "uint16");
got = dp(s, 'recv');
ix_chk('wbb_long_head', char(got(1:6)));
ix_chk('wbb_long_len', numel(got));
ix_chk('wbb_empty', dv_err(@() writebinblock(s, [], "uint8")));
ix_chk('wbb_no_prec', dv_err(@() writebinblock(s, 1:3)));
ix_chk('wbb_bad_prec', dv_err(@() writebinblock(s, 1:3, "uint9")));
ix_chk('nothing_sent_bb', ix_show(dp(s, 'recv')));

% binblock in
flush(s);
dp(s, sprintf('send %s', dp_hex(['#15' 1 2 3 4 5])));
pause(0.3);
ix_chk('rbb_uint8', ix_show(readbinblock(s)));
dp(s, sprintf('send %s', dp_hex(['#14' 1 0 2 0])));
pause(0.3);
ix_chk('rbb_uint16', ix_show(readbinblock(s, "uint16")));
dp(s, sprintf('send %s', dp_hex(['junk#13abc' 10])));
pause(0.3);
ix_chk('rbb_junk_char', ix_show(readbinblock(s, "char")));
ix_chk('rbb_after_left', s.NumBytesAvailable);
flush(s);
dp(s, sprintf('send %s', dp_hex(['#210' 0:9])));
pause(0.3);
ix_chk('rbb_two_digits', ix_show(readbinblock(s)));
dp(s, sprintf('send %s', dp_hex('#15abcde')));
pause(0.3);
ix_chk('rbb_string', ix_show(readbinblock(s, "string")));
flush(s);
[v, w] = dv_warn(@() readbinblock(s));
ix_chk('rbb_none', ix_show(v));
ix_chk('rbb_none_warn', w);
dp(s, sprintf('send %s', dp_hex('#15ab')));
pause(0.3);
[v, w] = dv_warn(@() readbinblock(s));
ix_chk('rbb_short', ix_show(v));
ix_chk('rbb_short_warn', w);
flush(s);
ix_chk('rbb_too_many', dv_err(@() readbinblock(s, "uint8", 1)));
