% record: -noFigureWindows
% U9 of the app-building plan (ADR 0207): how a tree and its nodes behave - the order of a tree's
% children, the selection and its refusals, what a deleted or a moved node leaves, a node's text,
% data and picture, the verbs move, expand and collapse, a check box tree's checked nodes - in a
% uifigure, with a classic figure tried at the end.
uf = uifigure('Visible', 'off', 'Position', [100 100 560 420]);
tr = uitree(uf);
u9_chk('children_empty', @() isempty(get(tr, 'Children')));
n1 = uitreenode(tr, 'Text', 'n1'); n2 = uitreenode(tr, 'Text', 'n2'); n3 = uitreenode(tr, 'Text', 'n3');
c1 = uitreenode(n1, 'Text', 'c1'); c2 = uitreenode(n1, 'Text', 'c2');
u9_chk('children_order', @() u9_texts(tr));
u9_chk('children_count', @() numel(get(tr, 'Children')));
u9_chk('node_children_count', @() numel(get(n1, 'Children')));
u9_chk('node_parent_type', @() get(get(c1, 'Parent'), 'Type'));
u9_chk('leaf_children_empty', @() isempty(get(c1, 'Children')));
u9_chk('figure_children_count', @() numel(get(uf, 'Children')));
u9_chk('findobj_nodes', @() numel(findobj(uf, 'Type', 'uitreenode')));
u9_chk('findobj_text', @() numel(findobj(tr, 'Text', 'c1')));
u9_chk('findall_nodes', @() numel(findall(uf, 'Type', 'uitreenode')));
u9_chk('allchild_tree', @() numel(allchild(tr)));
u9_chk('allchild_node', @() numel(allchild(n1)));
u9_chk('isa_node', @() double([isa(n1, 'matlab.ui.container.TreeNode') isa(n1, 'matlab.ui.container.Container') isa(n1, 'matlab.ui.control.Component') isa(n1, 'matlab.graphics.Graphics')]));
u9_chk('isa_tree', @() double([isa(tr, 'matlab.ui.container.Tree') isa(tr, 'matlab.ui.control.Component') isa(tr, 'matlab.ui.container.Container')]));
u9_chk('ancestor_figure', @() get(ancestor(c1, 'figure'), 'Type'));
u9_chk('ancestor_tree', @() get(ancestor(c1, 'uitree'), 'Type'));

% the selection
u9_chk('selected_default', @() isempty(get(tr, 'SelectedNodes')));
u9_chk('selected_one', @() u9_nodes(u9_sel(tr, n1)));
u9_chk('selected_two_single', @() u9_nodes(u9_sel(tr, [n1 n2])));
u9_chk('selected_empty', @() u9_nodes(u9_sel(tr, [])));
u9_chk('selected_cell', @() u9_nodes(u9_sel(tr, {n1})));
u9_chk('selected_number', @() u9_nodes(u9_sel(tr, 5)));
u9_chk('selected_tree', @() u9_nodes(u9_sel(tr, tr)));
u9_chk('selected_foreign', @() u9_nodes(u9_sel(tr, uitreenode(uitree(uf)))));
u9_chk('selected_nested', @() u9_nodes(u9_sel(tr, c1)));
set(tr, 'Multiselect', 'on');
u9_chk('multiselect_on', @() get(tr, 'Multiselect'));
u9_chk('selected_two_multi', @() u9_nodes(u9_sel(tr, [n1 n2])));
u9_chk('selected_column', @() u9_nodes(u9_sel(tr, [n1; n2])));
u9_chk('selected_duplicate', @() u9_nodes(u9_sel(tr, [n1 n1])));
u9_chk('selected_order', @() u9_nodes(u9_sel(tr, [n2 n1 c1])));
u9_chk('selected_with_foreign', @() u9_nodes(u9_sel(tr, [n1 uitreenode(uitree(uf))])));
set(tr, 'Multiselect', 'off');
u9_chk('multiselect_off_keeps_first', @() u9_nodes(get(tr, 'SelectedNodes')));
set(tr, 'Multiselect', 'on');
set(tr, 'SelectedNodes', n2);
delete(n2);
u9_chk('selected_after_delete', @() u9_nodes(get(tr, 'SelectedNodes')));
set(tr, 'SelectedNodes', c1);
delete(n1);
u9_chk('selected_after_parent_delete', @() u9_nodes(get(tr, 'SelectedNodes')));
u9_chk('valid_after_parent_delete', @() double([isvalid(n1) isvalid(c1) isvalid(c2)]));
u9_chk('children_after_deletes', @() u9_texts(tr));
mover = uitreenode(tr, 'Text', 'mover');
set(tr, 'SelectedNodes', mover);
other = uitree(uf);
set(mover, 'Parent', other);
u9_chk('selected_after_move_out', @() [u9_nodes(get(tr, 'SelectedNodes')) ' / ' u9_nodes(get(other, 'SelectedNodes'))]);
u9_chk('moved_node_tree', @() u9_texts(other));
delete(other);
u9_chk('valid_after_tree_delete', @() isvalid(mover));

% a node's own properties
u9_try('text_number', n3, 'Text', 5);
u9_try('text_string', n3, 'Text', "s");
u9_try('text_cell', n3, 'Text', {'a'});
u9_try('text_empty', n3, 'Text', '');
u9_try('text_strings', n3, 'Text', ["a" "b"]);
u9_try('text_matrix', n3, 'Text', ['ab'; 'cd']);
u9_try('nodedata_struct', n3, 'NodeData', struct('a', 1));
u9_try('nodedata_cell', n3, 'NodeData', {1, 'a'});
u9_try('nodedata_string', n3, 'NodeData', "s");
u9_try('nodedata_empty', n3, 'NodeData', []);
u9_try('icon_nofile', n3, 'Icon', 'nofile.png');
u9_try('icon_word', n3, 'Icon', 'error');
u9_try('icon_cube', n3, 'Icon', zeros(4, 4, 3));
u9_try('icon_number', n3, 'Icon', 5);
u9_try('icon_empty', n3, 'Icon', '');
u9_try('icon_empty_double', n3, 'Icon', []);
u9_try('icon_matrix', n3, 'Icon', ones(2, 2));
u9_try('icon_uint8', n3, 'Icon', uint8(zeros(2, 2, 3)));
u9_try('icon_over_one', n3, 'Icon', 2 * ones(2, 2, 3));
u2_chk('node_visible', @() get(n3, 'Visible'));
u2_chk('node_position', @() get(n3, 'Position'));
u2_chk('node_enable', @() get(n3, 'Enable'));
u2_chk('node_layout', @() get(n3, 'Layout'));
u2_err('node_to_grid', @() set(n3, 'Parent', uigridlayout(uf)));
u2_err('node_to_figure', @() set(n3, 'Parent', uf));
u2_err('node_to_listbox', @() set(n3, 'Parent', uilistbox(uf)));
u9_chk('tree_editable', @() u9_setget(tr, 'Editable', 'on'));
delete(allchild(uf));

% order and moves
tr = uitree(uf);
n1 = uitreenode(tr, 'Text', 'n1'); n2 = uitreenode(tr, 'Text', 'n2'); c1 = uitreenode(n1, 'Text', 'c1'); c2 = uitreenode(n1, 'Text', 'c2'); g1 = uitreenode(c1, 'Text', 'g1');
tr2 = uitree(uf); m1 = uitreenode(tr2, 'Text', 'm1');
u9_chk('texts_before', @() u9_texts(tr));
u9_run('move_to_sibling', @() move(c1, n2));
u9_chk('texts_after_move', @() u9_texts(tr));
u9_run('move_before', @() move(c1, c2, 'before'));
u9_chk('texts_after_before', @() u9_texts(tr));
u9_run('move_after', @() move(c1, c2, 'after'));
u9_chk('texts_after_after', @() u9_texts(tr));
u9_run('move_AFTER', @() move(c1, c2, 'AFTER'));
u9_run('move_bef', @() move(c1, c2, 'bef'));
u9_run('move_string_where', @() move(c1, c2, "before"));
u9_run('move_bogus_where', @() move(c1, c2, 'bogus'));
u9_run('move_too_many', @() move(c1, c2, 'before', 1));
u9_run('move_onto_itself', @() move(c1, c1));
u9_run('move_into_descendant', @() move(n1, g1));
u9_run('move_to_tree', @() move(c1, tr));
u9_run('move_to_figure', @() move(c1, uf));
u9_run('move_across_trees', @() move(c1, m1));
u9_chk('texts_after_across', @() [u9_texts(tr) ' / ' u9_texts(tr2)]);
u9_run('move_across_before', @() move(c1, m1, 'before'));
u9_chk('texts_after_across_before', @() [u9_texts(tr) ' / ' u9_texts(tr2)]);
u9_run('move_tree', @() move(tr, n1));
u9_run('move_one_argument', @() move(c1));
u9_run('move_number', @() move(5, n1));
u9_run('move_two_nodes', @() move([c2 g1], n2));
u9_run('children_reorder_bad', @() set(n1, 'Children', [g1; c2]));
u9_run('children_foreign', @() set(n1, 'Children', [c2; m1]));
u9_run('children_reorder', @() set(tr, 'Children', [n2; n1]));
u9_chk('texts_after_children', @() u9_texts(tr));
u9_run('parent_to_tree', @() set(c2, 'Parent', tr));
u9_chk('texts_after_parent', @() u9_texts(tr));
u9_run('parent_to_other_tree', @() set(c2, 'Parent', tr2));
u9_chk('texts_after_parent_other', @() [u9_texts(tr) ' / ' u9_texts(tr2)]);
u9_run('tree_to_classic', @() set(tr, 'Parent', figure('Visible', 'off')));
u9_chk('tree_classic_chain', @() u8_chain(n1));
u9_run('tree_back', @() set(tr, 'Parent', uf));
u9_chk('copy_tree', @() u9_texts(copyobj(tr, uf)));
u9_run('copy_node_to_figure', @() copyobj(n1, uf));

% expand and collapse
u9_run('expand_tree', @() expand(tr));
u9_run('expand_node', @() expand(n1));
u9_run('expand_leaf', @() expand(n2));
u9_run('expand_all', @() expand(tr, 'all'));
u9_run('expand_node_all', @() expand(n1, 'all'));
u9_run('expand_ALL', @() expand(tr, 'ALL'));
u9_run('expand_string_all', @() expand(tr, "all"));
u9_run('expand_bogus', @() expand(tr, 'bogus'));
u9_run('expand_node_arg', @() expand(tr, n1));
u9_run('expand_number_arg', @() expand(tr, 1));
u9_run('expand_two_nodes', @() expand([n1 n2]));
u9_run('expand_figure', @() expand(uf));
u9_run('expand_listbox', @() expand(uilistbox(uf)));
u9_run('expand_number', @() expand(5));
u9_run('collapse_tree', @() collapse(tr));
u9_run('collapse_node', @() collapse(n1));
u9_run('collapse_all', @() collapse(tr, 'all'));
u9_run('collapse_bogus', @() collapse(tr, 'bogus'));
u9_run('collapse_figure', @() collapse(uf));
delete(allchild(uf));

% a check box tree
ct = uitree(uf, 'checkbox');
p1 = uitreenode(ct, 'Text', 'p1'); p2 = uitreenode(ct, 'Text', 'p2');
k1 = uitreenode(p1, 'Text', 'k1'); k2 = uitreenode(p1, 'Text', 'k2'); k3 = uitreenode(k1, 'Text', 'k3');
u9_chk('checked_default', @() isempty(get(ct, 'CheckedNodes')));
u9_chk('checked_parent', @() u9_nodes(u9_check(ct, p1)));
u9_chk('checked_child_only', @() u9_nodes(u9_check(ct, k1)));
u9_chk('checked_all_children', @() u9_nodes(u9_check(ct, [k1 k2])));
u9_chk('checked_deepest', @() u9_nodes(u9_check(ct, k3)));
u9_chk('checked_two_leaves', @() u9_nodes(u9_check(ct, [k3 k2])));
u9_chk('checked_mixed', @() u9_nodes(u9_check(ct, [p2 k1])));
u9_chk('checked_column', @() u9_nodes(u9_check(ct, [p1; p2])));
u9_chk('checked_duplicate', @() u9_nodes(u9_check(ct, [p1 p1])));
u9_chk('checked_empty', @() u9_nodes(u9_check(ct, [])));
u9_chk('checked_number', @() u9_nodes(u9_check(ct, 5)));
u9_chk('checked_foreign', @() u9_nodes(u9_check(ct, uitreenode(uitree(uf, 'checkbox')))));
u9_chk('checked_plain_node', @() u9_nodes(u9_check(ct, uitreenode(uitree(uf)))));
u9_chk('checked_tree', @() u9_nodes(u9_check(ct, ct)));
u2_err('checked_on_plain_tree', @() set(uitree(uf), 'CheckedNodes', []));
u2_chk('checked_read_plain_tree', @() get(uitree(uf), 'CheckedNodes'));
u2_chk('multiselect_on_checkbox_tree', @() get(ct, 'Multiselect'));
u2_err('selected_two_on_checkbox_tree', @() set(ct, 'SelectedNodes', [p1 p2]));
set(ct, 'CheckedNodes', p2);
newborn = uitreenode(p2, 'Text', 'newborn');
u9_chk('checked_after_new_child', @() u9_nodes(get(ct, 'CheckedNodes')));
delete(newborn);
set(ct, 'CheckedNodes', [k2 k3]);
doomed = uitreenode(p1, 'Text', 'doomed');
set(ct, 'CheckedNodes', [get(ct, 'CheckedNodes'); doomed]);
u9_chk('checked_with_doomed', @() u9_nodes(get(ct, 'CheckedNodes')));
delete(doomed);
u9_chk('checked_after_delete', @() u9_nodes(get(ct, 'CheckedNodes')));
mover = uitreenode(ct, 'Text', 'mover');
set(ct, 'CheckedNodes', mover);
other = uitree(uf, 'checkbox');
set(mover, 'Parent', other);
u9_chk('checked_after_move_out', @() [u9_nodes(get(ct, 'CheckedNodes')) ' / ' u9_nodes(get(other, 'CheckedNodes'))]);
u9_chk('checkbox_texts', @() u9_texts(ct));
delete(uf);

% a classic figure holds the same trees
f = figure('Visible', 'off', 'Position', [100 100 560 420]);
tr = uitree(f); n1 = uitreenode(tr, 'Text', 'n1'); c1 = uitreenode(n1, 'Text', 'c1');
u9_chk('F_type', @() get(tr, 'Type'));
u9_chk('F_class_count', @() numel(fieldnames(get(tr))));
u9_chk('F_texts', @() u9_texts(tr));
u9_chk('F_selected', @() u9_nodes(u9_sel(tr, c1)));
ct = uitree(f, 'checkbox'); p1 = uitreenode(ct, 'Text', 'p1'); uitreenode(p1, 'Text', 'k1');
u9_chk('F_checked', @() u9_nodes(u9_check(ct, p1)));
delete(f);
