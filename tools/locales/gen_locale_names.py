"""Writes src/JGraph.Scripting/Jgs/JgsLocaleNames.cs from a record_locale_names.m table (ADR 0359).

Usage: python gen_locale_names.py names.tsv path/to/JgsLocaleNames.cs

Each row of the table is: locale, format field (MMM, MMMM, MMMMM, eee, eeee, eeeee, a), and the
texts R2025b prints for it joined with ';' (months January first, weekdays Sunday first, then AM
and PM). A row whose field is ERR is a locale R2025b does not recognize and is left out.
"""
import sys

FIELDS = ["MMM", "MMMM", "MMMMM", "eee", "eeee", "eeeee", "a"]
COUNTS = {"M": 12, "e": 7, "a": 2}


def main(table, out):
    header = ""
    rows = {}
    with open(table, encoding="utf-8-sig") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            if line.startswith("#"):
                header = line[1:].strip()
                continue
            locale, field, texts = line.split("\t")
            if field == "ERR":
                continue
            names = texts.split(";")
            if len(names) != COUNTS[field[0]] or any("|" in n for n in names):
                raise SystemExit(f"bad row: {line!r}")
            rows.setdefault(locale, {})[field] = texts

    lines = []
    for locale in sorted(rows, key=str.lower):
        fields = rows[locale]
        missing = [f for f in FIELDS if f not in fields]
        if missing:
            raise SystemExit(f"{locale} lacks {missing}")
        for field in FIELDS:
            lines.append(f"{locale}|{field}|{fields[field]}")

    body = "\n".join(lines)
    text = f'''// <auto-generated>
// Written by tools/locales/gen_locale_names.py from R2025b's own answers ({header}),
// recorded by tools/locales/record_locale_names.m. Do not edit by hand; record and regenerate.
// </auto-generated>

namespace JGraph.Scripting.Jgs;

/// <summary>
/// The month and weekday names and the AM/PM words R2025b prints for a datetime format's
/// <c>MMM</c>, <c>MMMM</c>, <c>MMMMM</c>, <c>eee</c>, <c>eeee</c>, <c>eeeee</c> and <c>a</c> under a
/// locale (open item 316, ADR 0359).
/// </summary>
internal static partial class JgsLocaleNames
{{
    /// <summary>
    /// One locale and field a line: the locale, the field, and its texts joined with ';' (months
    /// January first, weekdays Sunday first, AM then PM).
    /// </summary>
    private const string NameTable = """
{body}
""";
}}
'''
    with open(out, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
