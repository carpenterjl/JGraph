"""Writes src/JGraph.Scripting/Jgs/JgsTimeZoneNames.cs from a record_zone_names.m table (ADR 0350).

Usage: python gen_zone_names.py zones.tsv path/to/JgsTimeZoneNames.cs

Each row of the table is: name, stored TimeZone (or ERR), warning id, 'z' in January, its isdst,
'z' in July, its isdst. Names R2025b refuses, and names it stores as a fixed offset or UTC (those
are JgsTimeZones.Read's), are left out. A 'z' text is an abbreviation unless it is UTC or UTC with
an offset, which is R2025b's fallback for a zone the 'en' locale has no short name for and is
computed from the offset instead.
"""
import re
import sys

FALLBACK = re.compile(r"^UTC([+-].*)?$")
FIXED = re.compile(r"^([+-]\d\d:\d\d(:\d\d)?|UTC)$")


def main(table, out):
    header = ""
    names = []
    abbreviations = {}
    with open(table, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            if line.startswith("#"):
                header = line[1:].strip()
                continue
            name, stored, warn, jan, jan_dst, jul, jul_dst = line.split("\t")
            if stored == "ERR" or FIXED.match(stored):
                continue
            warned = warn == "MATLAB:datetime:NonstandardTimeZone"
            names.append((name, stored, warned))
            std, dst = abbreviations.get(stored, (None, None))
            for text, flag in ((jan, jan_dst), (jul, jul_dst)):
                if FALLBACK.match(text):
                    continue
                if flag == "1":
                    dst = dst or text
                else:
                    std = std or text
            if std or dst:
                abbreviations[stored] = (std, dst)

    rows = []
    for name, stored, warned in sorted(names, key=lambda r: r[0]):
        target = "=" if stored == name else stored
        rows.append(f"{name} {target}{' !' if warned else ''}")
    abbrev_rows = [f"{k} {v[0] or '-'} {v[1] or '-'}" for k, v in sorted(abbreviations.items())]

    body = "\n".join(rows)
    abbrev_body = "\n".join(abbrev_rows)
    text = f'''// <auto-generated>
// Written by tools/timezones/gen_zone_names.py from R2025b's own answers ({header}),
// recorded by tools/timezones/record_zone_names.m. Do not edit by hand; record and regenerate.
// </auto-generated>

namespace JGraph.Scripting.Jgs;

/// <summary>
/// The zone names R2025b accepts, matched with their case, what each is stored as, and whether it
/// warns <c>MATLAB:datetime:NonstandardTimeZone</c>; and the 'en' abbreviations its <c>z</c> letter
/// prints (ADR 0350).
/// </summary>
internal static partial class JgsTimeZoneNames
{{
    /// <summary>
    /// One name a line: the name, then <c>=</c> when it is stored as written or the name it is
    /// stored as, then <c>!</c> when R2025b warns that it does not name a single zone.
    /// </summary>
    private const string NameTable = """
{body}
""";

    /// <summary>
    /// One stored zone a line: its standard abbreviation and its daylight-saving one, <c>-</c> where
    /// the 'en' locale has none and R2025b prints the offset instead.
    /// </summary>
    private const string AbbreviationTable = """
{abbrev_body}
""";
}}
'''
    with open(out, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)
    print(f"{len(rows)} names, {len(abbrev_rows)} abbreviated zones")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
