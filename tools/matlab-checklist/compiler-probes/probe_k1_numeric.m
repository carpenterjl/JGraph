function probe_k1_numeric()
%PROBE_K1_NUMERIC More strings through mclisnumerictype, the rule mcc -n applies to a deployed
%main's arguments (compiler and SDK plan, stage K1; probe_k0_numeric has the first set and what
%eval made of them). Only the answer is printed: 1 or 0, never an eval. Run under matlab -batch.
beep('off');
cases = {'1+pi', '1+a', '[1 pi]', '3*2', '1/2', '2^3', '(1+2)*3', 'i', '1i', '1j', '2j', ...
    '.e', '.', '+', '-', '[', ']', '(', ')', 'x1', '0x', '0xG', '0x1f', '0X1F', '0b2', '0B11', ...
    '"txt"', '''', '''a''b', '1e5i', '[1;2]', '{1}', '1:3', '@sin', '~1', '1==1', '#', '%', ...
    '1%2', ',', ';', '1;', '[1 2]''', '1''', '1e+3', '1e-3', '1d3', '1D3', '1.2.3', '..', ...
    'e', 'E', 'ee', '1ee', '1e1e1', '[e]', '[1 e]', '(e)', '-e', '+i', '-j', '[i]', '[j]', ...
    '1_', '_1', '1a', '1x', '12x', '0x1Fu8', '0x1Fs8', '0x1Fu16', '1u8', 'Inf1', '1Inf', ...
    '1 + 2', ' ', '  ', sprintf('\t1'), sprintf('1\t'), '[1	2]', '1,', ',1', '[1,]', ...
    'a', 'z', 'A', 'Z', '1A', '1F', 'F', '[1 2 ; 3 4]', '[ ]', '( )', '()', '[[1]]', '((1))', ...
    '[1 (2)]', '-(1)', '+-1', '1+-2', '1*-2', '1--2', '1++2', 'true1', 'i1', 'j1', '3e', 'x'};
% Every case is char, as a deployed main's arguments are. A string scalar crashes R2025b inside
% mclisnumerictype (heap corruption, 0xc0000374, seen 2026-10-21): never pass one.
for k = 1:numel(cases)
    s = cases{k};
    try
        fprintf('[%s]\t%d\n', strrep(s, sprintf('\t'), '\t'), mclisnumerictype(s));
    catch ME
        fprintf('[%s]\tERR %s | %s\n', s, ME.identifier, strrep(ME.message, newline, ' / '));
    end
end
end
