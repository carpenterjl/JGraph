function v = k9make(kind)
%K9MAKE Return a value of the kind asked for, for the client to convert.
switch kind
    case 'double', v = 2.5;
    case 'negzero', v = -0;
    case 'row', v = [1 2 3];
    case 'column', v = [1; 2; 3];
    case 'matrix', v = [1 2 3; 4 5 6];
    case 'nd', v = reshape(1:24, 2, 3, 4);
    case 'nd4', v = reshape(1:16, 2, 2, 2, 2);
    case 'trailing', v = reshape(1:6, 1, 3, 2);
    case 'empty', v = [];
    case 'empty03', v = zeros(0, 3);
    case 'single', v = single(1.5);
    case 'singles', v = single([1.5 2.5]);
    case 'int8', v = int8(-5);
    case 'int8s', v = int8([-5 0 127]);
    case 'uint8', v = uint8(200);
    case 'uint8m', v = uint8([1 2; 3 4]);
    case 'int16', v = int16(-7);
    case 'uint16', v = uint16(7);
    case 'int32', v = int32(-100000);
    case 'int32s', v = int32([1 2 3]);
    case 'uint32', v = uint32(4000000000);
    case 'int64', v = int64(-9007199254740993);
    case 'uint64', v = uint64(18446744073709551615);
    case 'complex', v = 1-1i;
    case 'complexrow', v = [1+2i, 3-4i];
    case 'complexsingle', v = single(2+3i);
    case 'complexint8', v = int8(complex(1, 2));
    case 'logical', v = true;
    case 'logicals', v = [true false true];
    case 'logicalm', v = [true false; false true];
    case 'char', v = 'hello';
    case 'char1', v = 'x';
    case 'charmatrix', v = ['abc'; 'def'];
    case 'emptychar', v = '';
    case 'unicode', v = char([955 8364 65]);
    case 'string', v = "alpha";
    case 'strings', v = ["alpha", "beta"];
    case 'stringm', v = ["a" "b"; "c" "d"];
    case 'stringmissing', v = string(missing);
    case 'stringsmissing', v = [string(missing), "x"];
    case 'emptystring', v = "";
    case 'stringempty', v = string.empty(1, 0);
    case 'cell', v = {1, 'two', [3 4; 5 6]};
    case 'cellcol', v = {1; 'two'};
    case 'cellm', v = {1, 2; 3, 4};
    case 'cellstr', v = {'one', 'two'};
    case 'cellstrcol', v = {'one'; 'two'};
    case 'nestedcell', v = {{1}, {}};
    case 'emptycell', v = {};
    case 'struct', v = struct('name', 'probe', 'value', [1 2 3]);
    case 'structnested', v = struct('inner', struct('x', 1), 'list', {{1, 'a'}});
    case 'structarray', v = struct('a', {1, 2, 3});
    case 'structm', v = repmat(struct('a', 1), 2, 2);
    case 'emptystruct', v = struct([]);
    case 'nofields', v = struct();
    case 'sparse', v = sparse([1 3], [1 2], [5 6], 3, 3);
    case 'sparselogical', v = sparse([true false; false true]);
    case 'sparsecomplex', v = sparse([1+1i 0; 0 2]);
    case 'inf', v = [Inf -Inf NaN];
    case 'nan', v = NaN;
    case 'pi', v = pi;
    case 'enum', v = k9color.green;
    case 'enums', v = [k9color.red k9color.blue];
    case 'point', v = k9point(3, 4);
    case 'points', v = [k9point(1, 2) k9point(3, 4)];
    case 'counter', v = k9counter(5);
    case 'dict', v = dictionary(["a" "b"], [1 2]);
    case 'dictnum', v = dictionary([1 2 3], ["x" "y" "z"]);
    case 'dictcell', v = dictionary(["p" "q"], {1, 'two'});
    case 'dictempty', v = dictionary;
    case 'dictconfigured', v = configureDictionary("string", "double");
    case 'handle', v = @sin;
    case 'datetime', v = datetime(2026, 10, 24);
    case 'table', v = table([1; 2], ["a"; "b"]);
    case 'map', v = containers.Map({'k'}, {1});
    case 'categorical', v = categorical({'lo', 'hi'});
    case 'duration', v = seconds(90);
    otherwise, error('k9:kind', 'No kind %s.', kind);
end
end
