function v = k17_make(kind)
%K17_MAKE Answers a value of the kind named, for what each MATLAB class becomes in a Variant (stage K17).
switch kind
    case 'double', v = 3.5;
    case 'doublerow', v = [1 2 3];
    case 'doublecol', v = [1; 2; 3];
    case 'doublemat', v = [1 2; 3 4];
    case 'double3d', v = reshape(1:8, 2, 2, 2);
    case 'doubleneg0', v = -0;
    case 'bigint', v = 2^53;
    case 'single', v = single(1.5);
    case 'singlemat', v = single([1.25 2.5]);
    case 'int8', v = int8(-5);
    case 'uint8', v = uint8(200);
    case 'uint8mat', v = uint8([1 2; 3 4]);
    case 'int16', v = int16(-300);
    case 'uint16', v = uint16(60000);
    case 'int32', v = int32(-70000);
    case 'uint32', v = uint32(4000000000);
    case 'int64', v = int64(9007199254740993);
    case 'uint64', v = uint64(18446744073709551615);
    case 'logical', v = true;
    case 'logicalfalse', v = false;
    case 'logicalmat', v = [true false; false true];
    case 'logicalempty', v = logical([]);
    case 'char', v = 'hello';
    case 'charone', v = 'h';
    case 'charmat', v = ['ab'; 'cd'];
    case 'charcol', v = ['a'; 'b'];
    case 'charempty', v = '';
    case 'charnonascii', v = sprintf('caf\x00e9 \x2014 \x00b0');
    case 'charnewline', v = sprintf('one\ntwo');
    case 'string', v = "str";
    case 'stringarr', v = ["a" "bb"; "ccc" ""];
    case 'stringmissing', v = string(missing);
    case 'stringempty', v = strings(0);
    case 'cell', v = {1, 'two', [3 4]};
    case 'cellnested', v = {1, {2, 'x'}};
    case 'cellcol', v = {1; 2};
    case 'cellmat', v = {1, 'a'; 2, 'b'};
    case 'cellempty', v = {};
    case 'cellofempty', v = {[], '', {}};
    case 'struct', v = struct('a', 1, 'b', 'text');
    case 'structarr', v = struct('a', {1, 2}, 'b', {'x', 'y'});
    case 'structcol', v = struct('a', {1; 2});
    case 'structnested', v = struct('in', struct('x', 1, 'y', [1 2]));
    case 'structempty', v = struct([]);
    case 'structnofields', v = struct();
    case 'complex', v = 1 + 2i;
    case 'complexmat', v = [1+2i, 3-4i];
    case 'complexzero', v = complex(1, 0);
    case 'sparse', v = sparse([1 0; 0 2]);
    case 'sparselogical', v = sparse([true false]);
    case 'sparseempty', v = sparse(2, 2);
    case 'empty', v = [];
    case 'emptyrow', v = zeros(1, 0);
    case 'emptycol', v = zeros(0, 1);
    case 'nan', v = NaN;
    case 'nanmat', v = [1 NaN; NaN 4];
    case 'inf', v = Inf;
    case 'neginf', v = -Inf;
    case 'datetime', v = datetime(2024, 3, 15, 10, 30, 0);
    case 'datetimearr', v = datetime(2024, 3, [15 16], 0, 0, 0);
    case 'datetimenat', v = NaT;
    case 'datenum', v = 739326.4375;
    case 'duration', v = hours(1.5);
    case 'categorical', v = categorical({'a', 'b', 'a'});
    case 'fhandle', v = @sin;
    case 'fhandleanon', v = @(x) x + 1;
    case 'table', v = table([1; 2], {'a'; 'b'}, 'VariableNames', {'n', 's'});
    case 'map', v = containers.Map({'k'}, {1});
    case 'object', v = k17_thing(7);
    otherwise, error('k17:make', 'No kind %s', kind);
end
end
