  for f = 1:2
    try
      j = mps.json.encode(vals{k,2},'Format',fmts{f});
      fprintf('ENC [%s] %-24s : %s\n', fmts{f}, vals{k,1}, j);
      try
        d = mps.json.decode(j);
        fprintf('    DEC -> class=%s size=%s isequal=%d', class(d), mat2str(size(d)), isequaln(d, vals{k,2}));
        if isnumeric(d), fprintf(' isreal=%d', isreal(d)); end
        fprintf('\n');
      catch e2
        fprintf('    DEC ERR %s : %s\n', e2.identifier, e2.message);
      end
    catch e
      fprintf('ENC [%s] %-24s : ERR %s : %s\n', fmts{f}, vals{k,1}, e.identifier, e.message);
    end
  end
end
