function w15_sizes
% W15 (App Designer window plan): the words R2025b's property validation uses for a size that does not
% fit (MATLAB:validation:IncompatibleSize) over the sizes the Add Property dialog writes - against the
% arguments block's words for the same sizes - so that a managed property's refusal reads as R2025b's.
beep('off');
here = fileparts(mfilename('fullpath'));
rt = fullfile(here, 'rt', 'w15sizes');
if isfolder(rt), rmdir(rt, 's'); end
mkdir(rt);
fid = fopen(fullfile(rt, 'W15Sized.m'), 'w');
fprintf(fid, ['classdef W15Sized < handle\n' ...
    '    properties\n' ...
    '        A (1,1) double = 0;\n' ...
    '        B (1,2) double = [0 0];\n' ...
    '        C (:,1) double = 0;\n' ...
    '        D (1,:) double = 0;\n' ...
    '        E (2,2) double = zeros(2);\n' ...
    '        F (1,3) double = [0 0 0];\n' ...
    '        G (3,1) double = [0;0;0];\n' ...
    '        H (:,:) double = 0;\n' ...
    '        I (1,1) string = "";\n' ...
    '        J (2,:) double = zeros(2,1);\n' ...
    '        K (1,1) logical = false;\n' ...
    '    end\n' ...
    'end\n']);
fclose(fid);
fid = fopen(fullfile(rt, 'w15sizedfn.m'), 'w');
fprintf(fid, ['function w15sizedfn(a, b, c, d, e)\n' ...
    'arguments\n' ...
    '    a (1,1) double = 0\n' ...
    '    b (1,2) double = [0 0]\n' ...
    '    c (:,1) double = 0\n' ...
    '    d (2,2) double = zeros(2)\n' ...
    '    e (1,3) double = [0 0 0]\n' ...
    'end\n' ...
    'end\n']);
fclose(fid);
previous = cd(rt);
restore = onCleanup(@() cd(previous));
say('release %s', version('-release'));
o = W15Sized;
cases = {'A', [1 2]; 'A', []; 'A', [1;2]; 'B', [1 2 3]; 'B', [1;2]; 'B', 5; 'B', []; 'C', [1 2]; 'C', ones(2, 2); 'D', [1;2]; 'D', ones(2,3); 'E', [1 2]; 'E', ones(3); 'E', 5; 'F', [1 2]; 'F', ones(3, 1); 'G', [1 2 3]; 'G', ones(2, 2); 'H', ones(2,2,2); 'I', ["a" "b"]; 'J', ones(3, 2); 'J', [1 2]; 'K', [true false]};
for k = 1:size(cases, 1)
    try
        o.(cases{k, 1}) = cases{k, 2};
        say('property %s <- %s: ok (%s)', cases{k, 1}, mat2str(size(cases{k, 2})), mat2str(size(o.(cases{k, 1}))));
    catch e
        say('property %s <- %s: %s | %s', cases{k, 1}, mat2str(size(cases{k, 2})), e.identifier, strrep(e.message, newline, ' / '));
    end
end
fcases = {1, [1 2]; 2, [1 2 3]; 2, [1;2]; 3, [1 2]; 4, [1 2]; 5, ones(3, 1)};
for k = 1:size(fcases, 1)
    args = {0, [0 0], 0, zeros(2), [0 0 0]};
    args{fcases{k, 1}} = fcases{k, 2};
    try
        w15sizedfn(args{:});
        say('argument %d <- %s: ok', fcases{k, 1}, mat2str(size(fcases{k, 2})));
    catch e
        say('argument %d <- %s: %s | %s', fcases{k, 1}, mat2str(size(fcases{k, 2})), e.identifier, strrep(e.message, newline, ' / '));
    end
end
say('w15_sizes done');
end

function say(varargin)
fprintf([varargin{1} '\n'], varargin{2:end});
end
