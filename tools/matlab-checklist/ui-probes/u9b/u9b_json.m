    v = enc{k};
    try
        t = jsonencode(v);
        fprintf('enc %-50s => %s\n', deep(v), t);
    catch e
        fprintf('enc %-50s => ERR %s | %s\n', deep(v), e.identifier, oneline(e.message));
    end
end
% options
