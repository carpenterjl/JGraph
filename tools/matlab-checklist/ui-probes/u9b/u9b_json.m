    {struct('a', {}), 'PrettyPrint', true}, {{}, 'PrettyPrint', true}, {struct('a', {1, 2}), 'PrettyPrint', true}};
for k = 1:numel(opts)
    o = opts{k};
    try
        t = jsonencode(o{:});
        fprintf('encopt %-40s => %s\n', strjoin(cellfun(@deep, o, 'UniformOutput', false), ' '), strrep(t, newline, '\n'));
    catch e
        fprintf('encopt %-40s => ERR %s | %s\n', strjoin(cellfun(@deep, o, 'UniformOutput', false), ' '), e.identifier, oneline(e.message));
    end
end

